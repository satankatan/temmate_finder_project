    def clean_text(self, text: str) -> str:
        if not text or not isinstance(text, str):
            return ""

        text = text.lower().strip()
        text = self._emoji_pattern.sub(" ", text)
        text = re.sub(r"[^\w\s:]", " ", text)
        text = self._replace_gaming_slang(text)
        text = self._lemmatize_preserve_keywords(text)
        text = self._remove_stopwords_preserve_keywords(text)
        return " ".join(text.split())

    def _replace_gaming_slang(self, text: str) -> str:
        words = text.split()
        normalized = [self.gaming_slang_dict.get(word, word) for word in words]
        text = " ".join(normalized)

        for slang, normal in sorted(self.gaming_slang_dict.items(), key=lambda x: -len(x[0])):
            text = re.sub(r"\b" + re.escape(slang) + r"\b", normal, text)

        return text

    def _lemmatize_preserve_keywords(self, text: str) -> str:
        if not self._morph:
            return text

        words = []
        for word in text.split():
            if word in self.gaming_keywords or word in self.gaming_slang_dict.values():
                words.append(word)
                continue
            parsed = self._morph.parse(word)
            if parsed:
                words.append(parsed[0].normal_form)
            else:
                words.append(word)
        return " ".join(words)

    def _remove_stopwords_preserve_keywords(self, text: str) -> str:
        words = text.split()
        filtered = [
            word
            for word in words
            if (word not in self.stop_words or word in self.gaming_keywords)
            and len(word) > 2
        ]
        return " ".join(filtered)

    def preprocess_for_training(self, texts: List[str]) -> List[str]:
        return [self.clean_text(text) for text in texts if text]


