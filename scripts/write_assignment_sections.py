def set_text(paragraph, text: str):
    for run in paragraph.runs:
        run.text = ""
    run = paragraph.runs[0] if paragraph.runs else paragraph.add_run()
    run.text = text


def insert_after(paragraph, text: str, style=None) -> Paragraph:
    new_p = OxmlElement("w:p")
    paragraph._p.addnext(new_p)
    new_para = Paragraph(new_p, paragraph._parent)
    if style is not None:
        new_para.style = style
    set_text(new_para, text)
    return new_para


def main():
    doc = Document(TARGET)

    anchor_idx = None
    for i, p in enumerate(doc.paragraphs):
        if p.text.strip() == "ЗАДАНИЕ ОБУЧАЮЩЕГОСЯ НА ПРАКТИКУ":
            anchor_idx = i
            break
    if anchor_idx is None:
        raise RuntimeError("Не найден раздел задания")

    # Уже заполнено?
    nxt = doc.paragraphs[anchor_idx + 1].text.strip() if anchor_idx + 1 < len(doc.paragraphs) else ""
    if nxt == "Исходные данные":
        print("Раздел задания уже заполнен")
        return

    anchor = doc.paragraphs[anchor_idx]
    h2_style = None
    body_style = anchor.style
    for p in doc.paragraphs:
        if "Heading 2" in p.style.name:
            h2_style = p.style
            break

    last = anchor
    for kind, text in SECTIONS:
        style = h2_style if kind == "Heading 2" else body_style
        last = insert_after(last, text, style)

    try:
        doc.save(TARGET)
        print(f"Заполнен раздел задания: {TARGET}")
    except PermissionError:
        doc.save(FALLBACK)
        print(f"Основной файл занят Word. Сохранено в: {FALLBACK}")


if __name__ == "__main__":
    main()
