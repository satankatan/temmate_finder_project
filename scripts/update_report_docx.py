def is_appendix_code_paragraph(p, appendix_started=False):
    t = p.text.strip()
    if t.startswith("ПРИЛОЖЕНИЕ"):
        return False
    if not appendix_started:
        return False
    if t.startswith("[Здесь размещается"):
        return False
    if not t:
        return False
    code_markers = (
        "import ", "def ", "class ", "return ", "cursor.execute",
        "logger.", "self.", "try:", "except", "CREATE TABLE",
    )
    return any(m in t for m in code_markers)


